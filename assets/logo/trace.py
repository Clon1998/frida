"""Builds Frida's logo from Patrick's one-line Westie drawing (`westie-drawing.png`).

    python3 assets/logo/trace.py

Needs Python with Pillow and numpy, and potrace (`brew install potrace`). Writes:
- `assets/app-icon.svg`: the app icon, a white line on the indigo square. Turn it into every
  platform's icons with `cd app && pnpm tauri icon ../assets/app-icon.svg`.
- `assets/logo/westie.svg`: the dog alone, filled with `currentColor`, for the UI (copied to
  `app/ui/public/` for the start screen and the favicon).

How: crop the drawing to the dog, upscale it 3× (smoother curves), thicken the line by
`THICKEN` pixels (of the original drawing) so it survives small icon sizes, then let potrace
turn the bitmap into vector paths.
"""

import re
import subprocess
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).parent
DRAWING = HERE / "westie-drawing.png"
ICON = HERE.parent / "app-icon.svg"
MARK = HERE / "westie.svg"

THICKEN = 3  # pixels of the original drawing ("thin" was picked over 5 and 7)
SCALE = 3
# The dog's size in the 1024×1024 icon: at most this wide/high, centred on the square.
MAX_WIDTH, MAX_HEIGHT = 610.0, 530.0


def trace() -> tuple[str, float, float]:
    """The traced dog: potrace's `<g>` element and its width/height in its own units."""
    img = Image.open(DRAWING).convert("L")
    ys, xs = np.where(np.array(img) < 128)
    pad = 20
    crop = img.crop((xs.min() - pad, ys.min() - pad, xs.max() + pad, ys.max() + pad))
    big = crop.resize((crop.width * SCALE, crop.height * SCALE), Image.LANCZOS)
    ink = np.array(big) < 140

    # Thicken by "stamping" a disk of radius r at every line pixel (a morphological dilation).
    r = int(round(THICKEN * SCALE))
    yy, xx = np.mgrid[-r : r + 1, -r : r + 1]
    disk = (xx * xx + yy * yy) <= r * r
    h, w = ink.shape
    padded = np.pad(ink, r)
    thick = np.zeros_like(ink)
    for dy, dx in zip(*np.nonzero(disk)):
        thick |= padded[dy : dy + h, dx : dx + w]

    with tempfile.TemporaryDirectory() as tmp:
        pbm = Path(tmp) / "dog.pbm"
        traced = Path(tmp) / "dog.svg"
        Image.fromarray(np.where(thick, 0, 255).astype(np.uint8)).convert("1").save(pbm)
        subprocess.run(
            ["potrace", str(pbm), "-s", "-o", str(traced), "--turdsize", "40",
             "--alphamax", "1.1", "--opttolerance", "0.4"],
            check=True,
        )
        svg = traced.read_text()
    width = float(re.search(r'width="([\d.]+)pt"', svg).group(1))
    height = float(re.search(r'height="([\d.]+)pt"', svg).group(1))
    group = re.search(r"(<g transform=.*?</g>)", svg, re.S).group(1)
    return group, width, height


def main() -> None:
    group, width, height = trace()

    s = min(MAX_WIDTH / width, MAX_HEIGHT / height)
    tx, ty = 512 - width * s / 2, 512 - height * s / 2 + 10
    white = group.replace('fill="#000000"', 'fill="#ffffff"')
    ICON.write_text(f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <!-- Generated by assets/logo/trace.py from westie-drawing.png. -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#312e81"/>
      <stop offset="1" stop-color="#1e1b4b"/>
    </linearGradient>
  </defs>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#bg)"/>
  <g transform="translate({tx:.2f} {ty:.2f}) scale({s:.5f})">
    {white}
  </g>
</svg>
""")

    mark = group.replace('fill="#000000"', 'fill="currentColor"')
    MARK.write_text(f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width:.0f} {height:.0f}">
  <!-- Generated by assets/logo/trace.py from westie-drawing.png. -->
  {mark}
</svg>
""")
    print(f"wrote {ICON} and {MARK}")


if __name__ == "__main__":
    main()
